import { creationOrder } from './toTables.js'

// توليد CREATE TABLE لـ MySQL وPostgreSQL وSQLite (T6.2)

export const DIALECTS = {
  mysql: {
    label: 'MySQL',
    quote: (n) => `\`${n}\``,
    types: {
      string: 'VARCHAR(255)',
      text: 'TEXT',
      int: 'INT',
      decimal: 'DECIMAL(10,2)',
      boolean: 'BOOLEAN',
      date: 'DATE',
      datetime: 'DATETIME',
    },
    autoPk: (type) => `${type} AUTO_INCREMENT`,
    tableSuffix: ' ENGINE=InnoDB DEFAULT CHARSET=utf8mb4',
    inlineComment: true,
  },
  postgres: {
    label: 'PostgreSQL',
    quote: (n) => `"${n}"`,
    types: {
      string: 'VARCHAR(255)',
      text: 'TEXT',
      int: 'INTEGER',
      decimal: 'NUMERIC(10,2)',
      boolean: 'BOOLEAN',
      date: 'DATE',
      datetime: 'TIMESTAMP',
    },
    autoPk: () => 'INTEGER GENERATED ALWAYS AS IDENTITY',
    tableSuffix: '',
    indexFks: true,
  },
  sqlite: {
    label: 'SQLite',
    quote: (n) => `"${n}"`,
    types: {
      string: 'TEXT',
      text: 'TEXT',
      int: 'INTEGER',
      decimal: 'NUMERIC',
      boolean: 'INTEGER',
      date: 'TEXT',
      datetime: 'TEXT',
    },
    autoPk: () => 'INTEGER',
    tableSuffix: '',
    indexFks: true,
    // SQLite لا يتحقق من وجود الجدول المشار إليه وقت الإنشاء، فلا حاجة لـ ALTER
    inlineAllFks: true,
  },
}

// كلمات محجوزة شائعة تُحاط بعلامات التنصيص إن استُعملت أسماءً
const RESERVED = new Set(
  'user users order group table select from where key index date desc asc by limit check column default primary foreign references unique values time timestamp'.split(
    ' ',
  ),
)

const sqlString = (s) => `'${String(s).replace(/'/g, "''")}'`

export function toSQL(tables, dialect = 'mysql', { title } = {}) {
  const d = DIALECTS[dialect]
  const id = (n) => (RESERVED.has(n) ? d.quote(n) : n)
  const { order, deferred } = creationOrder(tables)
  const deferredSet = new Set(
    d.inlineAllFks ? [] : deferred.map((x) => `${x.table}.${x.fk.column}`),
  )
  const out = []

  out.push(`-- ${title ? `${title} — ` : ''}${d.label}`, '-- Generated by Bunyan')
  if (dialect === 'sqlite') out.push('PRAGMA foreign_keys = ON;')
  out.push('')

  for (const t of order) {
    const pks = t.columns.filter((c) => c.pk)
    const singlePk = pks.length === 1 ? pks[0] : null
    const defs = t.columns.map((c) => {
      let def
      if (c === singlePk && c.autoIncrement) {
        def = `${id(c.name)} ${d.autoPk(d.types.int)} PRIMARY KEY`
        if (dialect === 'sqlite') def += ' AUTOINCREMENT'
      } else {
        def = `${id(c.name)} ${d.types[c.type] ?? d.types.string}`
        if (c === singlePk) def += ' PRIMARY KEY'
        else if (c.notNull) def += ' NOT NULL'
        if (c.unique) def += ' UNIQUE'
      }
      if (d.inlineComment && c.label) def += ` COMMENT ${sqlString(c.label)}`
      return { def, comment: !d.inlineComment && c.label ? c.label : null }
    })
    if (pks.length > 1) defs.push({ def: `PRIMARY KEY (${pks.map((c) => id(c.name)).join(', ')})` })
    for (const fk of t.foreignKeys) {
      if (deferredSet.has(`${t.name}.${fk.column}`)) continue
      defs.push({
        def: `FOREIGN KEY (${id(fk.column)}) REFERENCES ${id(fk.refTable)}(${id(fk.refColumn)})${fk.onDelete ? ` ON DELETE ${fk.onDelete}` : ''}`,
      })
    }

    if (t.label) out.push(`-- ${t.label}`)
    out.push(`CREATE TABLE ${id(t.name)} (`)
    defs.forEach(({ def, comment }, i) => {
      const comma = i < defs.length - 1 ? ',' : ''
      out.push(`  ${def}${comma}${comment ? ` -- ${comment}` : ''}`)
    })
    out.push(
      `)${d.tableSuffix}${d.inlineComment && t.label ? ` COMMENT=${sqlString(t.label)}` : ''};`,
    )

    if (dialect === 'postgres') {
      if (t.label) out.push(`COMMENT ON TABLE ${id(t.name)} IS ${sqlString(t.label)};`)
      for (const c of t.columns)
        if (c.label)
          out.push(`COMMENT ON COLUMN ${id(t.name)}.${id(c.name)} IS ${sqlString(c.label)};`)
    }
    if (d.indexFks)
      for (const fk of t.foreignKeys)
        if (!t.columns.find((c) => c.name === fk.column)?.pk)
          out.push(
            `CREATE INDEX ${id(`idx_${t.name}_${fk.column}`)} ON ${id(t.name)}(${id(fk.column)});`,
          )
    out.push('')
  }

  // مفاتيح الحلقات تُضاف بعد إنشاء كل الجداول
  for (const { table, fk } of d.inlineAllFks ? [] : deferred)
    out.push(
      `ALTER TABLE ${id(table)} ADD CONSTRAINT ${id(`fk_${table}_${fk.column}`)} FOREIGN KEY (${id(fk.column)}) REFERENCES ${id(fk.refTable)}(${id(fk.refColumn)});`,
    )

  return out.join('\n').trim() + '\n'
}
